export function fillScene(id, tokens = {}) {
  const raw = SCENES[id]
  if (!raw) return null
  const fill = (t) => String(t ?? '').replaceAll('[WINNER]', tokens.winner || 'the surviving team')
  return {
    ...raw,
    id,
    title: fill(raw.title),
    subtitle: fill(raw.subtitle),
    kicker: fill(raw.kicker),
    lines: raw.lines.map(fill),
    src: raw.art ? ART[raw.art] : null,
  }
}

export function teamLabel(p1, p2) {
  const a = String(p1 || '').trim()
  const b = String(p2 || '').trim()
  if (a && b) return `Operators ${a} and ${b}`
  if (a || b) return `Operator ${a || b}`
  return ''
}
